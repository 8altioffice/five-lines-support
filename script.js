function renderContent(lang) {
    const t = translations[lang] || translations.en;

    // Header HTML is static (Logo), so we modify main content
    let html = `<h1>${t.title}</h1>`;
    html += `<p>${t.intro}</p><hr>`;

    // FAQ Section
    html += `<h2>${t.faqTitle}</h2>`;
    t.faqs.forEach(item => {
        html += `<h3>${item.q}</h3><p>${item.a}</p>`;
    });

    html += `<hr>`;

    // Contact Section
    html += `<h2>${t.contactTitle}</h2>`;
    html += `<p>${t.contactText}</p>`;

    // Contact Box
    html += `
    <div style="margin-top: 24px; padding: 20px; background: rgba(245, 240, 230, 0.05); border-radius: 12px; border-left: 4px solid var(--accent-mustard);">
        <p style="margin-bottom: 8px;"><strong>${t.emailLabel}</strong></p>
        <p style="margin-bottom: 16px;">destek8altioffice@gmail.com</p>
        <a href="mailto:destek8altioffice@gmail.com" class="contact-btn">${t.sendEmailBtn}</a>
    </div>
  `;

    html += `<hr>`;

    // Additional Resources
    html += `<h3>${t.resourcesTitle}</h3>`;
    html += `<ul><li><a href="https://8altioffice.github.io/five-lines/privacy.html">${t.privacyLink}</a></li></ul>`;

    document.getElementById('content').innerHTML = html;
    document.querySelector('footer p').innerHTML = t.footer;
}

document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
        document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        renderContent(btn.dataset.lang);
        document.documentElement.lang = btn.dataset.lang;
    });
});

// Load default or browser language
const browserLang = navigator.language.split('-')[0];
const defaultLang = translations[browserLang] ? browserLang : 'en';
document.querySelector(`[data-lang="${defaultLang}"]`)?.classList.add('active');
renderContent(defaultLang);
